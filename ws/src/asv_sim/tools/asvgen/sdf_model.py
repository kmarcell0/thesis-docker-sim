"""Serialise a Boat into an SDF document (string)."""
from . import __version__
from .xml_utils import E, V, pose, comment, to_string


def to_sdf(boat):
    cfg, base, hy = boat.cfg, boat.base, boat.hydro
    ixx, iyy, izz, ixy, ixz, iyz = base.sdf_inertia
    base_link = E(
        'link',
        comment('everything rigidly attached, lumped into one inertial about its centre of gravity'),
        E('inertial', pose(base.cog),
          V('mass', base.mass),
          E('inertia', V('ixx', ixx), V('iyy', iyy), V('izz', izz),
            V('ixy', ixy), V('ixz', ixz), V('iyz', iyz))),
        boat.visuals,
        boat.collisions,
        comment('sensors (topic and frame names follow the sensor name in the YAML)'),
        [el for part in boat.parts for el in part.sdf],
        name='base_link')
    model = E(
        'model',
        comment(f'GENERATED by asvgen {__version__} from config "{cfg["name"]}" '
                f'(fingerprint {boat.fingerprint}) - do not edit by hand'),
        comment(f'total mass {boat.total.mass:.2f} kg, draft {hy.draft * 100:.1f} cm, '
                f'spawn at z = {-hy.z_water + 0.02:.3f} m'),
        base_link,
        boat.links,
        boat.plugins,
        name=cfg['name'])
    return to_string(E('sdf', model, version='1.9'))


def model_config(boat):
    return to_string(E('model',
                       V('name', boat.cfg['name']),
                       V('version', '1.0'),
                       E('sdf', text='model.sdf', version='1.9'),
                       V('description', f'Catamaran ASV, two steerable thrusters. GENERATED by asvgen '
                                        f'(fingerprint {boat.fingerprint}).')))
