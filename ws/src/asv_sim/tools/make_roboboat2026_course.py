#!/usr/bin/env python3
"""Generate RoboBoat 2026 course elements + world for Gazebo Harmonic / VRX.

Every dimension marked [HB] comes from the RoboBoat 2026 Team Handbook,
section 3.2 Task Descriptions. Everything marked [EST] is an estimate
(the handbook shows layouts only as figures, and some element plans are
only in the registered-teams Data Sharing folder) - adjust freely.

Run:  python3 make_roboboat2026_course.py   (writes ../models and ../worlds)
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MODELS = os.path.join(HERE, '..', 'models')
WORLDS = os.path.join(HERE, '..', 'worlds')
IN = 0.0254  # inch -> metre
FT = 0.3048  # foot -> metre

# ----------------------------------------------------------------------------
# Colours (RGB 0..1)
# ----------------------------------------------------------------------------
RED = '0.80 0.05 0.05'
GREEN = '0.05 0.60 0.15'
BLACK = '0.03 0.03 0.03'
YELLOW = '0.95 0.80 0.05'
WHITE = '0.92 0.92 0.92'
BEIGE = '0.85 0.78 0.62'

WAVEFIELD = '<wavefield><topic>/vrx/wavefield/parameters</topic></wavefield>'


def material(rgb):
    return (f'<material><ambient>{rgb} 1</ambient><diffuse>{rgb} 1</diffuse>'
            f'<specular>0.2 0.2 0.2 1</specular></material>')


def write_model(name, sdf_body, description, static=False):
    d = os.path.join(MODELS, name)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, 'model.config'), 'w') as f:
        f.write(f'''<?xml version="1.0"?>
<model>
  <name>{name}</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>{description.replace('&', '&amp;')}</description>
</model>
''')
    with open(os.path.join(d, 'model.sdf'), 'w') as f:
        f.write(f'''<?xml version="1.0"?>
<!-- {description}
     Generated by tools/make_roboboat2026_course.py - edit the script, not this file. -->
<sdf version="1.9">
  <model name="{name}">
{'    <static>true</static>' if static else ''}
{sdf_body}
  </model>
</sdf>
''')


def inertia(ixx, iyy, izz):
    return (f'<inertia><ixx>{ixx:.5f}</ixx><iyy>{iyy:.5f}</iyy><izz>{izz:.5f}</izz>'
            '<ixy>0</ixy><ixz>0</ixz><iyz>0</iyz></inertia>')


def buoyancy_plugin(geometry, pose_z, linear_drag, angular_drag):
    return f'''    <plugin name="vrx::PolyhedraBuoyancyDrag" filename="libPolyhedraBuoyancyDrag.so">
      <fluid_density>1000</fluid_density>
      <fluid_level>0.0</fluid_level>
      <linear_drag>{linear_drag}</linear_drag>
      <angular_drag>{angular_drag}</angular_drag>
      <buoyancy name="buoyancy_volume">
        <link_name>link</link_name>
        <pose>0 0 {pose_z:.4f} 0 0 0</pose>
        <geometry>{geometry}</geometry>
      </buoyancy>
      {WAVEFIELD}
    </plugin>'''


# ----------------------------------------------------------------------------
# 1. Taylor Made Sur-Mark marker buoys (Task 1 entry/exit gates)
#    [HB] 39 in above waterline, 18 in diameter, red 950410 (port),
#    green 950400 (starboard). Link origin = waterline.
# ----------------------------------------------------------------------------
def surmark(name, rgb, desc):
    r = 18 * IN / 2                 # 0.2286 m
    top = 39 * IN                   # 0.9906 m above water
    bottom = -0.10                  # [EST] submerged depth
    body_top = top - r              # hemisphere on top of the cylinder
    cyl_len = body_top - bottom
    cyl_z = (body_top + bottom) / 2
    # mass so that the waterline is at z=0: displaced volume below z=0
    mass = 1000 * math.pi * r * r * (-bottom)          # ~16.4 kg
    h = top - bottom
    ixx = mass * (3 * r * r + h * h) / 12
    izz = mass * r * r / 2
    geom_cyl = f'<cylinder><radius>{r:.4f}</radius><length>{cyl_len:.4f}</length></cylinder>'
    body = f'''    <link name="link">
      <inertial>
        <pose>0 0 -0.05 0 0 0</pose>  <!-- ballast low: self-righting -->
        <mass>{mass:.2f}</mass>
        {inertia(ixx, ixx, izz)}
      </inertial>
      <visual name="body">
        <pose>0 0 {cyl_z:.4f} 0 0 0</pose>
        <geometry>{geom_cyl}</geometry>
        {material(rgb)}
      </visual>
      <visual name="dome">
        <pose>0 0 {body_top:.4f} 0 0 0</pose>
        <geometry><sphere><radius>{r:.4f}</radius></sphere></geometry>
        {material(rgb)}
      </visual>
      <collision name="collision">
        <pose>0 0 {(top + bottom) / 2:.4f} 0 0 0</pose>
        <geometry><cylinder><radius>{r:.4f}</radius><length>{h:.4f}</length></cylinder></geometry>
      </collision>
    </link>
{buoyancy_plugin(f'<cylinder><radius>{r:.4f}</radius><length>0.4</length></cylinder>', bottom + 0.2, 50.0, 10.0)}'''
    write_model(name, body, desc)


# ----------------------------------------------------------------------------
# 2. Polyform A-series round buoys
#    [HB] A-0: 20.3 cm diameter, 0.5 ft above waterline (Task 2)
#    [HB] A-2: 36.8 cm diameter, 1 ft above waterline (Task 3)
#    Modelled as spheres (rope-hold eye on top omitted). Link origin = waterline.
# ----------------------------------------------------------------------------
def polyform(name, diameter, above, rgb, desc):
    r = diameter / 2
    cz = above - r                   # sphere centre height above waterline
    h = r - cz                       # submerged cap height
    vol = math.pi * h * h * (3 * r - h) / 3
    mass = 1000 * vol                # floats exactly at the handbook height
    i = 0.4 * mass * r * r
    geom = f'<sphere><radius>{r:.4f}</radius></sphere>'
    body = f'''    <link name="link">
      <inertial>
        <pose>0 0 {cz - 0.3 * r:.4f} 0 0 0</pose>
        <mass>{mass:.3f}</mass>
        {inertia(i, i, i)}
      </inertial>
      <visual name="visual">
        <pose>0 0 {cz:.4f} 0 0 0</pose>
        <geometry>{geom}</geometry>
        {material(rgb)}
      </visual>
      <collision name="collision">
        <pose>0 0 {cz:.4f} 0 0 0</pose>
        <geometry>{geom}</geometry>
      </collision>
    </link>
{buoyancy_plugin(geom, cz, 10.0 if diameter < 0.3 else 20.0, 1.0 if diameter < 0.3 else 2.0)}'''
    write_model(name, body, desc)
    return mass


# ----------------------------------------------------------------------------
# 3. Colour indicator buoy (Tasks 2 and 3)
#    [HB] custom buoy ~18 in square base, white with black diamonds,
#    red OR green indicator cylinder on top, 1 ft above waterline.
#    [HB, Task 5 table] indicator cylinder 5.2 in H x 5 in W.
#    [EST] base thickness, mast, mass. Link origin = waterline.
# ----------------------------------------------------------------------------
def indicator_buoy(name, rgb, desc):
    side = 18 * IN                   # 0.457 m
    base_h, base_z = 0.10, 0.03      # base spans -0.02 .. 0.08
    ind_h, ind_r = 5.2 * IN, 5 * IN / 2
    top = 1 * FT
    ind_z = top - ind_h / 2
    mast_bot, mast_top = base_z + base_h / 2, top - ind_h
    mass = 1000 * side * side * 0.02  # waterline at z=0 with 2 cm draft
    ixx = mass * (side * side + base_h * base_h) / 12
    izz = mass * (2 * side * side) / 12
    diamonds = []
    for k, (px, py, rpy, size) in enumerate([
            (side / 2 + 0.002, 0, '0.7854 0 0', '0.004 0.05 0.05'),
            (-side / 2 - 0.002, 0, '0.7854 0 0', '0.004 0.05 0.05'),
            (0, side / 2 + 0.002, '0 0.7854 0', '0.05 0.004 0.05'),
            (0, -side / 2 - 0.002, '0 0.7854 0', '0.05 0.004 0.05')]):
        diamonds.append(f'''      <visual name="diamond_{k}">
        <pose>{px:.4f} {py:.4f} {base_z:.4f} {rpy}</pose>
        <geometry><box><size>{size}</size></box></geometry>
        {material(BLACK)}
      </visual>''')
    box = f'<box><size>{side:.4f} {side:.4f} {base_h}</size></box>'
    body = f'''    <link name="link">
      <inertial>
        <pose>0 0 0 0 0 0</pose>
        <mass>{mass:.2f}</mass>
        {inertia(ixx, ixx, izz)}
      </inertial>
      <visual name="base">
        <pose>0 0 {base_z} 0 0 0</pose>
        <geometry>{box}</geometry>
        {material(WHITE)}
      </visual>
{chr(10).join(diamonds)}
      <visual name="mast">
        <pose>0 0 {(mast_bot + mast_top) / 2:.4f} 0 0 0</pose>
        <geometry><cylinder><radius>0.03</radius><length>{mast_top - mast_bot:.4f}</length></cylinder></geometry>
        {material(WHITE)}
      </visual>
      <visual name="indicator">
        <pose>0 0 {ind_z:.4f} 0 0 0</pose>
        <geometry><cylinder><radius>{ind_r:.4f}</radius><length>{ind_h:.4f}</length></cylinder></geometry>
        {material(rgb)}
      </visual>
      <collision name="collision">
        <pose>0 0 {base_z} 0 0 0</pose>
        <geometry>{box}</geometry>
      </collision>
    </link>
{buoyancy_plugin(box, base_z, 25.0, 5.0)}'''
    write_model(name, body, desc)


# ----------------------------------------------------------------------------
# 4. Dock colour indicator (Task 5): [HB] solid cylinder 5.2 in H x 5 in W.
#    Static; model origin = bottom of the cylinder.
# ----------------------------------------------------------------------------
def dock_indicator(name, rgb, desc):
    h, r = 5.2 * IN, 5 * IN / 2
    geom = f'<cylinder><radius>{r:.4f}</radius><length>{h:.4f}</length></cylinder>'
    body = f'''    <link name="link">
      <visual name="visual">
        <pose>0 0 {h / 2:.4f} 0 0 0</pose>
        <geometry>{geom}</geometry>
        {material(rgb)}
      </visual>
      <collision name="collision">
        <pose>0 0 {h / 2:.4f} 0 0 0</pose>
        <geometry>{geom}</geometry>
      </collision>
    </link>'''
    write_model(name, body, desc, static=True)


# ----------------------------------------------------------------------------
# 5. Stationary vessel (coroplast boat), yellow or black.
#    [HB] dimensions only in Data Sharing -> [EST] 1.2 x 0.5 x 0.3 m open hull.
#    Floating. Link origin = waterline.
# ----------------------------------------------------------------------------
def vessel(name, rgb, desc):
    L, W, H, t = 1.2, 0.5, 0.3, 0.01
    draft = 0.01
    mass = 1000 * L * W * draft
    zc = H / 2 - draft
    parts = [  # name, x, y, z, sx, sy, sz
        ('bottom', 0, 0, -draft + t / 2, L, W, t),
        ('side_l', 0, W / 2 - t / 2, zc, L, t, H),
        ('side_r', 0, -W / 2 + t / 2, zc, L, t, H),
        ('bow', L / 2 - t / 2, 0, zc, t, W, H),
        ('stern', -L / 2 + t / 2, 0, zc, t, W, H)]
    vis = []
    for n, x, y, z, sx, sy, sz in parts:
        g = f'<box><size>{sx} {sy} {sz}</size></box>'
        vis.append(f'''      <visual name="{n}_visual">
        <pose>{x} {y} {z:.4f} 0 0 0</pose>
        <geometry>{g}</geometry>
        {material(rgb)}
      </visual>
      <collision name="{n}_collision">
        <pose>{x} {y} {z:.4f} 0 0 0</pose>
        <geometry>{g}</geometry>
      </collision>''')
    hull = f'<box><size>{L} {W} {H}</size></box>'
    body = f'''    <link name="link">
      <inertial>
        <pose>0 0 0.03 0 0 0</pose>
        <mass>{mass:.2f}</mass>
        {inertia(mass * (W * W + H * H) / 12, mass * (L * L + H * H) / 12, mass * (L * L + W * W) / 12)}
      </inertial>
{chr(10).join(vis)}
    </link>
{buoyancy_plugin(hull, zc, 40.0, 10.0)}'''
    write_model(name, body, desc)


# ----------------------------------------------------------------------------
# 6. Floating dock pier with 3 slips (Task 5), static.
#    [HB] cubes 20 x 20 x 16 in, beige; dock 40 in wide; tines 4-7 ft long;
#    two piers with three slips; 24 x 24 in black number banners.
#    [EST] slip width 5 ft, tine length 4 cubes (6.7 ft), freeboard 0.25 m,
#    backbone length (follows from slip width), banner placement.
#    Pier frame: slips open towards -x (boat drives in along +x),
#    slip 1 on the left (+y) as seen from the approaching boat.
# ----------------------------------------------------------------------------
CUBE = 20 * IN                      # 0.508 m
CUBE_H = 16 * IN                    # 0.406 m
DOCK_TOP = 0.25                     # [EST] freeboard
SLIP_W = 5 * FT                     # [EST] 1.524 m clear width
TINE_CUBES = 4                      # [EST] 4 cubes = 6.7 ft (handbook: 4-7 ft)
TINE_L = TINE_CUBES * CUBE
BACKBONE_D = 2 * CUBE               # [HB] 40 in wide dock
N_SLIPS = 3
PIER_LEN = (N_SLIPS + 1) * CUBE + N_SLIPS * SLIP_W
SLIP_Y = [PIER_LEN / 2 - CUBE - SLIP_W / 2 - k * (CUBE + SLIP_W) for k in range(N_SLIPS)]
BANNER = 24 * IN


def seven_segment(digit):
    """Return (u, v, su, sv) boxes for digits 1-3 (u right, v up), metres."""
    W, H, s = 0.11, 0.20, 0.05
    seg = {'a': (0, H - s / 2, 2 * W, s), 'd': (0, -H + s / 2, 2 * W, s),
           'g': (0, 0, 2 * W, s), 'b': (W - s / 2, H / 2, s, H),
           'c': (W - s / 2, -H / 2, s, H), 'e': (-W + s / 2, -H / 2, s, H),
           'f': (-W + s / 2, H / 2, s, H)}
    if digit == 1:
        return [(0, H / 2, s, H), (0, -H / 2, s, H)]
    names = {2: 'abged', 3: 'abgcd'}[digit]
    return [seg[c] for c in names]


def dock_pier(name, desc):
    zc = DOCK_TOP - CUBE_H / 2
    vis, col = [], []
    # backbone: 2 cubes deep (x) behind the tines
    xb0 = TINE_L
    ny = round(PIER_LEN / CUBE)
    for i in range(2):
        for j in range(ny):
            x = xb0 + CUBE / 2 + i * CUBE
            y = -PIER_LEN / 2 + CUBE / 2 + j * (PIER_LEN / ny)
            vis.append((f'bb_{i}_{j}', x, y, zc, CUBE - 0.01, PIER_LEN / ny - 0.01, CUBE_H, BEIGE))
    col.append(('backbone', xb0 + BACKBONE_D / 2, 0, zc, BACKBONE_D, PIER_LEN, CUBE_H))
    # tines between/around slips
    tine_y = [PIER_LEN / 2 - CUBE / 2 - k * (CUBE + SLIP_W) for k in range(N_SLIPS + 1)]
    for t, y in enumerate(tine_y):
        for i in range(TINE_CUBES):
            vis.append((f'tine_{t}_{i}', CUBE / 2 + i * CUBE, y, zc, CUBE - 0.01, CUBE - 0.01, CUBE_H, BEIGE))
        col.append((f'tine_{t}', TINE_L / 2, y, zc, TINE_L, CUBE, CUBE_H))
    # number banners on the backbone, facing the approaching boat (-x)
    bx = xb0 + BACKBONE_D - 0.15
    bz = DOCK_TOP + BANNER / 2
    for k, y in enumerate(SLIP_Y):
        vis.append((f'banner_{k + 1}', bx, y, bz, 0.02, BANNER, BANNER, BLACK))
        col.append((f'banner_{k + 1}', bx, y, bz, 0.02, BANNER, BANNER))
        for s, (u, v, su, sv) in enumerate(seven_segment(k + 1)):
            vis.append((f'digit_{k + 1}_{s}', bx - 0.013, y - u, bz + v, 0.006, su, sv, WHITE))
    out = ['    <link name="link">']
    for n, x, y, z, sx, sy, sz, rgb in vis:
        out.append(f'''      <visual name="{n}">
        <pose>{x:.4f} {y:.4f} {z:.4f} 0 0 0</pose>
        <geometry><box><size>{sx:.4f} {sy:.4f} {sz:.4f}</size></box></geometry>
        {material(rgb)}
      </visual>''')
    for n, x, y, z, sx, sy, sz in col:
        out.append(f'''      <collision name="{n}">
        <pose>{x:.4f} {y:.4f} {z:.4f} 0 0 0</pose>
        <geometry><box><size>{sx:.4f} {sy:.4f} {sz:.4f}</size></box></geometry>
      </collision>''')
    out.append('    </link>')
    write_model(name, '\n'.join(out), desc, static=True)


# ----------------------------------------------------------------------------
# Task (group) models: nested includes, so a whole task moves with one pose.
# ----------------------------------------------------------------------------
def include(name, uri, x, y, z=0.0, yaw=0.0, static=False):
    s = '<static>true</static>' if static else ''
    return (f'    <include>{s}<name>{name}</name><pose>{x:.3f} {y:.3f} {z:.3f} 0 0 {yaw:.4f}</pose>'
            f'<uri>model://{uri}</uri></include>')


def write_task(name, lines, desc):
    write_model(name, '\n'.join(lines), desc)


def main():
    # --- element models ----------------------------------------------------
    surmark('rb26_surmark_red', RED, 'Taylor Made Sur-Mark 950410, red (port marker). RoboBoat 2026 Task 1.')
    surmark('rb26_surmark_green', GREEN, 'Taylor Made Sur-Mark 950400, green (starboard marker). RoboBoat 2026 Task 1.')
    masses = {}
    for c, rgb in (('red', RED), ('green', GREEN), ('black', BLACK)):
        masses[f'a0_{c}'] = polyform(f'rb26_a0_{c}', 0.203, 0.5 * FT, rgb, f'Polyform A-0, {c}. RoboBoat 2026 Task 2.')
    for c, rgb in (('red', RED), ('green', GREEN), ('black', BLACK), ('yellow', YELLOW)):
        masses[f'a2_{c}'] = polyform(f'rb26_a2_{c}', 0.368, 1 * FT, rgb, f'Polyform A-2, {c}. RoboBoat 2026 Task 3.')
    indicator_buoy('rb26_indicator_buoy_red', RED, 'Colour indicator buoy, RED indicator. RoboBoat 2026 Tasks 2/3.')
    indicator_buoy('rb26_indicator_buoy_green', GREEN, 'Colour indicator buoy, GREEN indicator. RoboBoat 2026 Tasks 2/3.')
    dock_indicator('rb26_dock_indicator_red', RED, 'Dock colour indicator, red (slip occupied/unavailable). Task 5.')
    dock_indicator('rb26_dock_indicator_green', GREEN, 'Dock colour indicator, green (slip available). Task 5.')
    vessel('rb26_vessel_yellow', YELLOW, 'Stationary coroplast vessel, yellow (dimensions estimated).')
    vessel('rb26_vessel_black', BLACK, 'Stationary coroplast vessel, black (dimensions estimated).')
    dock_pier('rb26_dock_pier', 'Floating dock pier, 3 numbered slips. RoboBoat 2026 Task 5.')

    # --- Task 1: Evacuation Route & Return (entry/exit gates) ----------------
    # local frame: +x = direction of travel when ENTERING; red = port (+y)
    G1_WIDTH = 10 * FT        # [EST] buoy centre-to-centre
    G1_SPACING = 8.0          # [EST] distance between the two gates
    t1 = []
    for k, x in enumerate((0.0, G1_SPACING)):
        t1.append(include(f'gate{k + 1}_red_port', 'rb26_surmark_red', x, G1_WIDTH / 2))
        t1.append(include(f'gate{k + 1}_green_starboard', 'rb26_surmark_green', x, -G1_WIDTH / 2))
    write_task('rb26_task1_entry_exit', t1, 'RoboBoat 2026 Task 1 - Evacuation Route & Return: two Sur-Mark gates.')

    # --- Task 2: Debris Clearance (navigation channel + debris field) --------
    G2_WIDTH = 8 * FT          # [EST]
    t2 = []
    for k, x in enumerate((0.0, 6.0, 12.0)):            # [EST] 3 gates, 6 m apart
        t2.append(include(f'ch_gate{k + 1}_red', 'rb26_a0_red', x, G2_WIDTH / 2))
        t2.append(include(f'ch_gate{k + 1}_green', 'rb26_a0_green', x, -G2_WIDTH / 2))
    debris_black = [(17, 3.0), (19, -2.5), (22, 1.0), (24, 4.5), (25, -4.0),
                    (28, -1.0), (30, 3.0), (31, -3.5)]  # [EST] scattered
    for k, (x, y) in enumerate(debris_black):
        t2.append(include(f'debris_black_{k + 1}', 'rb26_a0_black', x, y))
    t2.append(include('indicator_hazard_1', 'rb26_indicator_buoy_red', 21, -5.5))
    t2.append(include('indicator_hazard_2', 'rb26_indicator_buoy_red', 29, 5.5))
    t2.append(include('indicator_survivor_1', 'rb26_indicator_buoy_green', 26, 1.5))
    t2.append(include('vessel_1', 'rb26_vessel_black', 33, 0.5, yaw=0.6))
    write_task('rb26_task2_debris_clearance', t2, 'RoboBoat 2026 Task 2 - Debris Clearance: A-0 channel gates + debris field.')

    # --- Task 3: Emergency Response Sprint ------------------------------------
    G3_WIDTH = 10 * FT         # [EST]
    t3 = [include('gate_red', 'rb26_a2_red', 0, G3_WIDTH / 2),
          include('gate_green', 'rb26_a2_green', 0, -G3_WIDTH / 2),
          include('color_indicator', 'rb26_indicator_buoy_red', 3.0, 3.5),   # red -> circle CCW
          include('obstacle_1', 'rb26_a2_black', 8.0, -1.5),
          include('obstacle_2', 'rb26_a2_black', 14.0, 1.5),
          include('mark_yellow', 'rb26_a2_yellow', 20.0, 0.0),
          include('vessel_1', 'rb26_vessel_yellow', 12.0, -6.0, yaw=1.2)]
    write_task('rb26_task3_speed_challenge', t3, 'RoboBoat 2026 Task 3 - Emergency Response Sprint.')

    # --- Task 5: Navigate the Marina ------------------------------------------
    # local frame: boat approaches along +x; dock N at +y, dock S at -y.
    PIER_GAP = 2.0             # [EST] water between the two piers
    pier_y = {'N': PIER_LEN / 2 + PIER_GAP / 2, 'S': -(PIER_LEN / 2 + PIER_GAP / 2)}
    # Example scenario (change freely, but follow the handbook rules:
    # a slip with a vessel is never green; a red slip may be empty).
    scenario = {('N', 1): ('red', 'yellow'), ('N', 2): ('red', None), ('N', 3): ('green', None),
                ('S', 1): ('green', None), ('S', 2): ('red', 'black'), ('S', 3): ('red', 'yellow')}
    t5 = []
    for dock, py in pier_y.items():
        t5.append(include(f'dock_{dock}', 'rb26_dock_pier', 0, py, static=True))
    for (dock, slip), (light, boat) in scenario.items():
        y = pier_y[dock] + SLIP_Y[slip - 1]
        t5.append(include(f'dock_{dock}_slip{slip}_indicator_{light}', f'rb26_dock_indicator_{light}',
                          TINE_L + 0.25, y, DOCK_TOP, static=True))
        if boat:
            t5.append(include(f'dock_{dock}_slip{slip}_vessel', f'rb26_vessel_{boat}', TINE_L / 2, y))
    write_task('rb26_task5_marina', t5, 'RoboBoat 2026 Task 5 - Navigate the Marina: 2 piers x 3 slips.')

    # --- report -----------------------------------------------------------------
    print('Masses (kg) of round buoys:', {k: round(v, 3) for k, v in masses.items()})
    print(f'Pier length {PIER_LEN:.2f} m, tine length {TINE_L:.2f} m, slip centres {[round(y, 3) for y in SLIP_Y]}')


if __name__ == '__main__':
    main()
